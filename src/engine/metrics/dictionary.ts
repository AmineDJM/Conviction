/**
 * §15 METRIC_DICTIONARY — the single place where metric meaning is defined.
 *
 * Nothing else in the codebase may define what a metric means. Scoring,
 * normalization, derivation and UI tooltips all read from here.
 */
import type { MetricKey } from "./keys";

export type MetricUnit = "USD" | "PERCENT" | "RATIO" | "COUNT" | "MONTHS" | "DAYS" | "MULTIPLE";
export type MetricPeriod = "POINT_IN_TIME" | "ANNUALIZED" | "PERIOD" | "MONTHLY";
export type MetricFamily =
  | "REVENUE"
  | "RETENTION"
  | "CUSTOMERS"
  | "UNIT_ECONOMICS"
  | "CASH"
  | "GTM"
  | "CONSUMER"
  | "MARKETPLACE"
  | "FINTECH"
  | "HARDWARE"
  | "DEEPTECH";

export interface MetricDefinition {
  key: MetricKey;
  name: string;
  shortName: string;
  family: MetricFamily;
  definition: string;
  formula: string | null;
  unit: MetricUnit;
  period: MetricPeriod;
  direction: "HIGHER_IS_BETTER" | "LOWER_IS_BETTER" | "CONTEXTUAL";
  /** Things that must be distinguished before the number is trusted. */
  disambiguation: string[];
  requiredFields: string[];
  exclusions: string[];
  quality: {
    minSampleSize?: number;
    minMeasurementMonths?: number;
    maxAgeMonths: number;
  };
  /** Metric keys from which this metric can be derived by code (see derive.ts). */
  derivableFrom?: MetricKey[];
}

